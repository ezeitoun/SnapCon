// test/connectors/virtual-u1-file.test.js — a file sent to the virtual U1
// prints as the file says (fixtures/virtual-u1/slicedFile.js): temperatures
// per tool, the bed, the tools it uses, layers, time, objects, ooze
// prevention. And the Virtual U1 printer type's Fast timing: every wait at
// once, the print 10 times faster.
//
// The test file is laid out like our SnapmakerOrca files for the U1 (header,
// thumbnails, executable block, objects, body, then "filament used", the
// estimate and the config block at the end), with made-up values.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const os = require("os");
const path = require("path");
const u1c = require("../../connectors/snapmaker-u1-klipper");
const vu1 = require("../../connectors/virtual-u1");
const { startVirtualU1, VirtualU1 } = require("../../fixtures/virtual-u1");
const { readSlicedFile, HEAD_BYTES, TAIL_BYTES } = require("../../fixtures/virtual-u1/slicedFile");

const EXT = ["extruder", "extruder1", "extruder2", "extruder3"];

// Seven filament slots, printing with tools 0 (215°C) and 4 (230°C).
function slicedFile({ bodyBytes = 4000, middle = "", ooze = 1, config = true } = {}) {
  const head = [
    "; HEADER_BLOCK_START",
    "; generated by Snapmaker Orca 2.4.0 on 2026-10-09 at 21:23:03",
    "; total layer number: 33",
    "; filament_density: 1.24,1.24,1.24,1.24,1.24,1.24,1.24",
    "; HEADER_BLOCK_END", "",
    "; THUMBNAIL_BLOCK_START", "; thumbnail begin 300x300 100", "; iVBORw0KGgoAAAANSUhEUgAA=", "; thumbnail end", "; THUMBNAIL_BLOCK_END", "",
    "; EXECUTABLE_BLOCK_START",
    "M73 P0 R81",
    "EXCLUDE_OBJECT_DEFINE NAME=Left_bracket.stl_id_0_copy_0 CENTER=120.5,80 POLYGON=[[110,70],[131,70],[131,90],[110,90]]",
    "EXCLUDE_OBJECT_DEFINE NAME=Right_bracket.stl_id_1_copy_0 CENTER=180,80 POLYGON=[[170,70],[190,70],[190,90],[170,90]]",
    "M104 S215 T0", ""
  ].join("\n");
  const filler = "G1 X10 Y10 E0.5\n".repeat(Math.ceil(bodyBytes / 16));
  const half = Math.floor(filler.length / 2);
  const body = filler.slice(0, half) + middle + filler.slice(half);
  const tail = [
    "; EXECUTABLE_BLOCK_END", "",
    "; filament used [g] = 8.10, 0.00, 0.00, 0.00, 17.40, 0.00, 0.00",
    "; estimated printing time (normal mode) = 1h 21m 16s",
    ...(config ? [
      "; CONFIG_BLOCK_START",
      "; curr_bed_type = Textured PEI Plate",
      "; filament_colour = #FFFFFF;#BF9573;#7C544F;#FF80C0;#000000;#C0C0C0;#FFC600",
      "; filament_settings_id = \"PLA (U1)\";\"PLA (U1)\";\"PLA (U1)\";\"PLA (U1)\";\"PETG (U1)\";\"PLA (U1)\";\"PLA (U1)\"",
      "; filament_type = PLA;PLA;PLA;PLA;PETG;PLA;PLA",
      "; first_layer_bed_temperature = 45",
      "; hot_plate_temp = 65,65,65,65,65,65,65",
      "; initial_layer_print_height = 0.2",
      "; layer_height = 0.16",
      "; nozzle_diameter = 0.4,0.4,0.4,0.4",
      "; nozzle_temperature = 215,215,215,215,230,215,215",
      "; ooze_prevention = " + ooze,
      "; preheat_time = 30",
      "; standby_temperature_delta = -150",
      "; textured_plate_temp = 45,45,45,45,45,45,45",
      "; CONFIG_BLOCK_END"] : []), ""
  ].join("\n");
  return Buffer.from(head + body + tail);
}

async function virtualU1(t, opts) {
  const u1 = await startVirtualU1(opts);
  t.after(() => u1.close());
  return { u1, p: { id: "virtual-" + u1.port, name: "Virtual U1", url: u1.url } };
}
const head = (u1, i) => u1.model.status()[EXT[i]];

// Sends the file the way SnapCon does (the real U1 connector's upload).
async function send(t, p, name, content) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "virtual-u1-file-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const local = path.join(dir, name);
  fs.writeFileSync(local, content);
  await u1c.uploadFile(p, local, name, { sent: 0, total: 0 });
}

// Tool 0 on head 1, tool 4 on head 2, then print.
async function print(u1, p, name) {
  await u1c.applyHeadMapping(p, [0, 4], { 0: 1, 4: 2 }, {});
  await u1c.startPrintFile(p, name);
}

test("reads what the file says, from its start and end", () => {
  const o = readSlicedFile(slicedFile());
  assert.deepEqual(o.tools, [0, 4], "the tools with filament used, not every slot");
  assert.deepEqual(o.nozzleTemps, [215, 215, 215, 215, 230, 215, 215]);
  assert.equal(o.bedTemp, 45, "the first-layer bed temperature of the plate used, not hot_plate_temp");
  assert.equal(o.colours[4], "#000000");
  assert.equal(o.types[4], "PETG");
  assert.equal(o.filamentNames[4], "PETG (U1)");
  assert.equal(o.oozePrevention, true);
  assert.equal(o.standbyDelta, -150);
  assert.equal(o.preheatTime, 30);
  assert.equal(o.layers, 33);
  assert.equal(o.estimatedSeconds, 3600 + 21 * 60 + 16);
  assert.equal(o.layerHeight, 0.16);
  assert.equal(o.firstLayerHeight, 0.2);
  assert.deepEqual(o.objectList.map(x => x.name), ["LEFT_BRACKET.STL_ID_0_COPY_0", "RIGHT_BRACKET.STL_ID_1_COPY_0"]);
  assert.deepEqual(o.objectList[0].center, [120.5, 80]);
  assert.equal(o.objectList[0].polygon.length, 4);
  assert.equal(o.slicer, "SnapmakerOrca");
  assert.equal(o.slicerVersion, "2.4.0");
});

test("the middle of a large file is never read", () => {
  // A config block in the middle, which the reader must not see.
  const decoy = "; nozzle_temperature = 280,280\n; first_layer_bed_temperature = 99\n";
  const big = slicedFile({ bodyBytes: HEAD_BYTES + TAIL_BYTES + 2 * 1024 * 1024, middle: decoy, config: false });
  const o = readSlicedFile(big);
  assert.equal(o.nozzleTemps, undefined);
  assert.equal(o.bedTemp, undefined);
  assert.equal(o.layers, 33, "the header is still read");
  assert.deepEqual(o.tools, [0, 4], "and the end");
});

test("a file sent to it prints at its own temperatures, on its own tools, with its own objects", async t => {
  const { u1, p } = await virtualU1(t);
  await send(t, p, "Brackets.gcode", slicedFile());

  const meta = await u1c.getFileMetadata(p, "Brackets.gcode");
  assert.equal(meta.estimatedTime, 3600 + 21 * 60 + 16);
  assert.equal(meta.palette.length, 7);
  const raw = u1.model.files.gcodes.get("Brackets.gcode").metadata;
  assert.equal(raw.layer_count, 33);
  assert.equal(raw.first_layer_bed_temp, 45);
  assert.equal(raw.first_layer_extr_temp, 215);
  assert.equal(raw.filament_type.split(";")[4], "PETG");

  await print(u1, p, "Brackets.gcode");
  const st = u1.model.status();
  assert.equal(st.heater_bed.target, 45);
  assert.equal(head(u1, 1).target, 215, "tool 0's head");
  assert.deepEqual(st.exclude_object.objects.map(o => o.name), ["LEFT_BRACKET.STL_ID_0_COPY_0", "RIGHT_BRACKET.STL_ID_1_COPY_0"]);

  // Through the first change: tool 4's head heats to 230, tool 0's head
  // waits at 215 - 150.
  let changed = false;
  for (let i = 0; i < 2000 && !changed; i++) {
    u1.model.advance(5);
    changed = u1.model.status().toolhead.extruder === "extruder2";
  }
  assert.ok(changed, "the change to tool 4's head happened");
  assert.equal(head(u1, 2).target, 230);
  assert.equal(head(u1, 1).target, 65);
  assert.equal(u1.model.status().print_stats.info.total_layer, 33);
  assert.equal(head(u1, 0).target, 0, "a head the file never uses stays off");
});

test("standby follows each tool's own temperature", async t => {
  const { u1, p } = await virtualU1(t);
  await send(t, p, "Brackets.gcode", slicedFile());
  await print(u1, p, "Brackets.gcode");
  // Through the change back, at the start of layer 2: tool 4's head waits at 230 - 150.
  let back = false, left = false;
  for (let i = 0; i < 4000 && !back; i++) {
    u1.model.advance(5);
    const ex = u1.model.status().toolhead.extruder;
    if (ex === "extruder2") left = true;
    back = left && ex === "extruder1";
  }
  assert.ok(back);
  assert.equal(head(u1, 2).target, 80);
  assert.equal(head(u1, 1).target, 215);
});

test("ooze prevention off: the parked head stays at print temperature, the next head heats at its change", async t => {
  const { u1, p } = await virtualU1(t);
  await send(t, p, "No ooze.gcode", slicedFile({ ooze: 0 }));
  await print(u1, p, "No ooze.gcode");
  let preheated = false, changed = false;
  for (let i = 0; i < 2000 && !changed; i++) {
    u1.model.advance(5);
    changed = u1.model.status().toolhead.extruder === "extruder2";
    if (!changed && head(u1, 2).target > 0) preheated = true;
  }
  assert.ok(changed);
  assert.equal(preheated, false, "no preheat before the change");
  assert.equal(head(u1, 1).target, 215, "no standby");
});

test("a file without settings keeps the defaults", async t => {
  const { u1, p } = await virtualU1(t);
  await send(t, p, "Plain.gcode", Buffer.from("G28\nG1 X10 Y10\n"));
  const plan = u1.model.files.gcodes.get("Plain.gcode").plan;
  assert.deepEqual(plan.tools, [0]);
  assert.equal(plan.bedTemp, 65);
  assert.deepEqual(plan.nozzleTemps, [215]);
  assert.equal(plan.layers, 20);
  assert.equal(u1.model.files.gcodes.get("Plain.gcode").content.toString(), "G28\nG1 X10 Y10\n", "the bytes sent are kept");
  await u1c.startPrintFile(p, "Plain.gcode");
  assert.equal(u1.model.status().heater_bed.target, 65);
});

test("printSpeed: the print runs that many times faster, and print_stats reports the file's time", () => {
  const m = new VirtualU1({ printSpeed: 10, instantHeat: true });
  m.addFile("Ten.gcode", { tools: [0], layers: 10, estimatedSeconds: 1000 });
  m.runScript("SDCARD_PRINT_FILE FILENAME=Ten.gcode");
  m.advance(1);
  assert.equal(m.status().extruder.temperature, 215, "instant heat: at temperature after one tick");
  assert.equal(m.status().heater_bed.temperature, 65);
  m.advance(60);
  const ps = m.status().print_stats;
  assert.ok(ps.total_duration >= 600, `the file's time moved 10x: ${ps.total_duration}`);
  m.advance(60);
  assert.equal(m.status().print_stats.state, "complete", "a 1000s print plus its start in ~2 minutes");
  assert.throws(() => new VirtualU1({ printSpeed: 0 }), /printSpeed must be above 0/);
});

test("printSpeed holds with many short tool segments: a tick runs through several (as on a real 4-colour file)", () => {
  const m = new VirtualU1({ printSpeed: 10, instantHeat: true });
  // 100 layers x 4 tools = 400 segments of 3.2s: at 10x a 0.25s tick is
  // 2.5s, so a segment ends inside a tick and the rest must carry over.
  m.addFile("Many.gcode", { tools: [0, 1, 2, 3], layers: 100, estimatedSeconds: 1280 });
  m.runScript("SDCARD_PRINT_FILE FILENAME=Many.gcode");
  m.advance(122, 0.25);
  assert.equal(m.status().print_stats.state, "printing", "not before its time");
  m.advance(10, 0.25);
  assert.equal(m.status().print_stats.state, "complete", "1280s of print plus its start, 10x, with the clock's own steps");
  assert.ok(Math.abs(m.history[0].print_duration - 1280) <= 1, `print_duration ${m.history[0].print_duration}`);
});

test("the Virtual U1 printer type: Fast is instant heat and 10x, Real is neither", async t => {
  t.after(() => vu1._closeAll());
  const ports = await Promise.all([0, 1].map(() => new Promise(r => {
    const s = require("net").createServer().listen(0, "127.0.0.1", () => { const { port } = s.address(); s.close(() => r(port)); });
  })));
  const fast = { id: "vu1-fast", name: "Fast", connector: "virtual-u1", port: ports[0], url: "http://127.0.0.1:" + ports[0], virtualTiming: "fast" };
  const real = { id: "vu1-real", name: "Real", connector: "virtual-u1", port: ports[1], url: "http://127.0.0.1:" + ports[1], virtualTiming: "real" };
  await vu1.probe(fast); await vu1.probe(real);
  const f = vu1._sims.get(ports[0]).sim.model, r = vu1._sims.get(ports[1]).sim.model;
  assert.deepEqual([f.timing, f.printSpeed, f.instantHeat], ["fast", 10, true]);
  assert.deepEqual([r.timing, r.printSpeed, r.instantHeat], ["real", 1, false]);
});
