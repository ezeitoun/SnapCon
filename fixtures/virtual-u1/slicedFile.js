// fixtures/virtual-u1/slicedFile.js — what a sliced G-code file says about
// itself, read the way a printer needs it to run the file: temperatures, the
// colours it prints with, its layers, its time and its objects. No I/O.
//
// Only the start and the end of the file are read, never the middle: the
// Virtual U1 runs inside SnapCon's process, and a file can be hundreds of MB.
// In our 62 SnapmakerOrca files for the U1 (2026-10-15) the settings block
// and "filament used" sat within the last 36KB, the layer count in the
// header, and the last EXCLUDE_OBJECT_DEFINE within the first 140KB.
const HEAD_BYTES = 512 * 1024;
const TAIL_BYTES = 128 * 1024;

const num = v => { const n = parseFloat(v); return Number.isFinite(n) ? n : undefined; };
const list = (v, sep) => (v == null ? undefined : String(v).split(sep).map(s => s.trim().replace(/^"(.*)"$/, "$1")));
const numList = v => { const l = list(v, ","); return l && l.every(x => num(x) !== undefined) ? l.map(num) : undefined; };

// "1d 2h 3m 4s", "58m 14s", "45s" → seconds.
function duration(text) {
  if (!text) return undefined;
  const units = { d: 86400, h: 3600, m: 60, s: 1 };
  let total = 0, found = false;
  for (const [, n, u] of String(text).matchAll(/(\d+)\s*([dhms])/g)) { total += +n * units[u]; found = true; }
  return found ? total : undefined;
}

// "; key = value" settings (the config block) and "; key: value" (the header).
function settings(text) {
  const out = {};
  for (const [, key, value] of text.matchAll(/^;\s*([^=:\n]+?)\s*[=:]\s*(.*?)\s*$/gm)) if (!(key in out)) out[key] = value;
  return out;
}

// EXCLUDE_OBJECT_DEFINE NAME=… CENTER=x,y POLYGON=[[x,y],…]. Klipper stores
// the name upper-cased [source exclude_object.py].
function objectsIn(text) {
  const objects = [];
  for (const [line] of text.matchAll(/^EXCLUDE_OBJECT_DEFINE .*$/gm)) {
    const name = (/NAME=(\S+)/.exec(line) || [])[1];
    if (!name) continue;
    const o = { name: name.toUpperCase() };
    const c = numList((/CENTER=(\S+)/.exec(line) || [])[1]);
    if (c && c.length === 2) o.center = c;
    try { const poly = JSON.parse((/POLYGON=(\[\S*\])/.exec(line) || [])[1]); if (Array.isArray(poly)) o.polygon = poly; } catch {}
    objects.push(o);
  }
  return objects;
}

// Returns the addFile options the file gives (model.js); a value the file
// does not have is left out, so the model's default applies.
function readSlicedFile(content) {
  const buf = Buffer.isBuffer(content) ? content : Buffer.from(String(content));
  const head = buf.subarray(0, HEAD_BYTES).toString("latin1");
  const tailStart = Math.max(0, buf.length - TAIL_BYTES);
  const tail = buf.subarray(tailStart).toString("latin1");
  // The tail wins where both have a key: the config block is the slicer's
  // own record of the settings.
  const s = { ...settings(head), ...settings(tail) };
  const opts = {};

  const weights = numList(s["filament used [g]"]);
  if (weights) {
    opts.weights = weights;
    const tools = weights.map((w, t) => (w > 0 ? t : -1)).filter(t => t >= 0);
    if (tools.length) opts.tools = tools;
  }
  const nozzle = numList(s.nozzle_temperature);
  if (nozzle) opts.nozzleTemps = nozzle;
  const bed = num(s.first_layer_bed_temperature);
  if (bed !== undefined) opts.bedTemp = bed;
  const colours = list(s.filament_colour, ";");
  if (colours) opts.colours = colours;
  const types = list(s.filament_type, ";");
  if (types) opts.types = types;
  const names = list(s.filament_settings_id, ";");
  if (names) opts.filamentNames = names;
  if (s.ooze_prevention !== undefined) opts.oozePrevention = s.ooze_prevention === "1";
  const delta = num(s.standby_temperature_delta);
  if (delta !== undefined) opts.standbyDelta = delta;
  const preheat = num(s.preheat_time);
  if (preheat !== undefined) opts.preheatTime = preheat;
  const layers = parseInt(s["total layer number"], 10);
  if (layers > 0) opts.layers = layers;
  const seconds = duration(s["estimated printing time (normal mode)"]);
  if (seconds > 0) opts.estimatedSeconds = seconds;
  const layerHeight = num(s.layer_height);
  if (layerHeight) opts.layerHeight = layerHeight;
  const firstLayerHeight = num(s.initial_layer_print_height);
  if (firstLayerHeight) opts.firstLayerHeight = firstLayerHeight;
  const diameter = numList(s.nozzle_diameter);
  if (diameter) opts.nozzleDiameter = diameter[0];
  const objects = objectsIn(head);
  if (objects.length) opts.objectList = objects;
  const by = /generated by (.+?) (\d[\w.]*)/.exec(head.slice(0, 4096));
  if (by) { opts.slicer = by[1].replace(/\s+/g, ""); opts.slicerVersion = by[2]; }
  // [guess] Moonraker's gcode_start_byte/gcode_end_byte: where the G-code
  // proper starts and ends, here the slicer's own markers.
  const start = head.indexOf("; EXECUTABLE_BLOCK_START");
  if (start >= 0) opts.gcodeStart = start;
  const end = tail.lastIndexOf("; EXECUTABLE_BLOCK_END");
  if (end >= 0) opts.gcodeEnd = tailStart + end;
  return opts;
}

module.exports = { readSlicedFile, HEAD_BYTES, TAIL_BYTES };
